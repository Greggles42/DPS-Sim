/**
 * Builds skillCapsData.js (exact player skill caps per class and level) from the EQMacEmu / Quarm server
 * skill_caps table.
 *
 * Source: the TAKP merge content SQL (the skill_caps rows the live server loads; identical to
 * utils/sql/git/required/2022_08_03_skill_caps.sql except for the shaman alchemy fix, which the sim doesn't use).
 *
 * Usage: node scripts/skill-caps-to-js.mjs [path-to-sql]
 * Default path: C:/Projects/EQMacEmu-src/utils/sql/git/content/2024_12_01_TAKP_Merge_20240717_to_20241109_Phase_03_20240926.sql
 *
 * Output shape: SkillCapsData.skills[key][classIndex] = null | [firstLevel, cap@first, cap@first+1, ...]
 *   classIndex 0..14 = WAR CLR PAL RNG SHD DRU MNK BRD ROG SHM NEC WIZ MAG ENC BST (server class id - 1).
 *   firstLevel is also the level the skill is first trained (server GetSkillTrainLevel).
 *   Above the last row the server keeps using the last row (GetSkillCapMaxLevel), so lookups clamp.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DEFAULT_SQL = 'C:/Projects/EQMacEmu-src/utils/sql/git/content/2024_12_01_TAKP_Merge_20240717_to_20241109_Phase_03_20240926.sql';
const sqlPath = process.argv[2] || DEFAULT_SQL;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// EQ::skills::SkillType ids (common/skills.h) for every skill the sim reads a class cap for.
const SKILLS = {
  '1hb': 0, '1hs': 1, '2hb': 2, '2hs': 3, archery: 7, backstab: 8, bash: 10, block: 11, defense: 15,
  dodge: 19, doubleAttack: 20, dragonPunch: 21, dualWield: 22, eagleStrike: 23, flyingKick: 26,
  h2h: 28, kick: 30, offense: 33, parry: 34, '1hp': 36, riposte: 37, roundKick: 38, throwing: 51, tigerClaw: 52
};

const sql = fs.readFileSync(sqlPath, 'utf8');
const rows = {}; // `${skillId}|${classId}` -> {level: cap}
let count = 0;
for (const m of sql.matchAll(/INSERT INTO skill_caps \(`id`, `skill_id`, `class_id`, `level`, `cap`, `class_`\) VALUES \((\d+), (\d+), (\d+), (\d+), (\d+), (\d+)\)/g)) {
  const skillId = +m[2], classId = +m[3], level = +m[4], cap = +m[5];
  const key = skillId + '|' + classId;
  (rows[key] || (rows[key] = {}))[level] = cap;
  count++;
}
if (!count) throw new Error('No skill_caps rows found in ' + sqlPath);

const skills = {};
for (const [name, id] of Object.entries(SKILLS)) {
  skills[name] = [];
  for (let classId = 1; classId <= 15; classId++) {
    const byLevel = rows[id + '|' + classId];
    if (!byLevel) { skills[name].push(null); continue; }
    const levels = Object.keys(byLevel).map(Number).sort((a, b) => a - b);
    const first = levels[0], last = levels[levels.length - 1];
    const arr = [first];
    for (let L = first; L <= last; L++) arr.push(byLevel[L] != null ? byLevel[L] : arr[arr.length - 1]);
    skills[name].push(arr);
  }
}

const out =
  '/* GENERATED by scripts/skill-caps-to-js.mjs from the Quarm server skill_caps table — do not edit by hand. */\n' +
  '(function (global) {\n  \'use strict\';\n  global.SkillCapsData = ' + JSON.stringify({ skills }) + ';\n})(typeof self !== \'undefined\' ? self : this);\n';
fs.writeFileSync(path.join(root, 'skillCapsData.js'), out);
console.log('Wrote skillCapsData.js from', count, 'rows;', Object.keys(SKILLS).length, 'skills;', (out.length / 1024).toFixed(1), 'KB');
