/**
 * Emit resources/bis-presets-data.js from the curated BiS CSV (works over file://, no fetch).
 * Run: node scripts/bis-presets-to-js.mjs
 *
 * CSV columns: Class,Slot,Item,Item ID,Notes,Drop Location
 * Edit the CSV to curate the lists, then re-run this script. Item ID is what the sim uses;
 * Item is only a display fallback. Rows for slots the sim has no equivalent for
 * (Two-Hander, Instruments) are skipped with a note. A Quiver row becomes a quiver weight-reduction % (Notes: "60% Weight Reduction").
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const res = path.join(__dirname, '..', 'resources');
const csvPath = path.join(res, 'Planes of Power BiS – All Classes - All Classes.csv');
const outPath = path.join(res, 'bis-presets-data.js');

const CLASS_IDS = {
  'Warrior': 'warrior', 'Cleric': 'cleric', 'Paladin': 'paladin', 'Ranger': 'ranger',
  'Shadow Knight': 'shadowknight', 'Shadowknight': 'shadowknight', 'Druid': 'druid', 'Monk': 'monk',
  'Bard': 'bard', 'Rogue': 'rogue', 'Shaman': 'shaman', 'Necromancer': 'necromancer',
  'Wizard': 'wizard', 'Magician': 'magician', 'Enchanter': 'enchanter', 'Beastlord': 'beastlord'
};
// CSV slot → inventory-manager slot key(s). Paired slots (Ears/Fingers/Wrists) take two CSV rows: the first
// row fills the first key, the second row the second. A lone row fills both so older lists still work.
const SLOT_KEYS = {
  'Primary': ['Primary'], 'Secondary': ['Secondary'], 'Ranged': ['Range'],
  'Ears': ['Ear', 'Ear2'], 'Neck': ['Neck'], 'Face': ['Face'], 'Head': ['Head'],
  'Fingers': ['Fingers', 'Fingers2'], 'Wrists': ['Wrist', 'Wrist2'], 'Arms': ['Arms'],
  'Hands': ['Hands'], 'Shoulders': ['Shoulders'], 'Chest': ['Chest'], 'Back': ['Back'],
  'Waist': ['Waist'], 'Legs': ['Legs'], 'Feet': ['Feet']
};

function parseCsv(text) {
  const rows = [];
  let row = [], cur = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"') { if (text[i + 1] === '"') { cur += '"'; i++; } else q = false; }
      else cur += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(cur); cur = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(cur); cur = '';
      if (row.some(v => v !== '')) rows.push(row);
      row = [];
    } else cur += c;
  }
  if (cur !== '' || row.length) { row.push(cur); rows.push(row); }
  return rows;
}

const text = fs.readFileSync(csvPath, 'utf8').replace(/^﻿/, '');
const rows = parseCsv(text);
rows.shift(); // header
const presets = {};
const skipped = [];
const seen = {};
for (const r of rows) {
  const [cls, slot, name, idStr] = r.map(v => v.trim());
  const classId = CLASS_IDS[cls];
  const id = parseInt(idStr, 10);
  if (!classId) { skipped.push(`unknown class "${cls}"`); continue; }
  // A quiver is a container, not an item the sim can equip. It matters only through its weight
  // reduction: Notes must contain "NN% Weight Reduction" (the sim derives bow haste as WR / 4).
  if (slot === 'Quiver' && classId) {
    const m = /(\d+(?:\.\d+)?)\s*%\s*Weight Reduction/i.exec(r[4] || '');
    if (m) (presets[classId] || (presets[classId] = {}))._quiverWR = Math.min(100, Math.round(parseFloat(m[1])));
    else skipped.push(`${cls}/Quiver (${name}): no "NN% Weight Reduction" in Notes`);
    continue;
  }
  const keys = SLOT_KEYS[slot];
  if (!keys) { skipped.push(`${cls}/${slot} (${name}): no matching sim slot`); continue; }
  if (isNaN(id)) { skipped.push(`${cls}/${slot} (${name}): missing Item ID`); continue; }
  const p = presets[classId] || (presets[classId] = {});
  const n = (seen[classId + '/' + slot] = (seen[classId + '/' + slot] || 0) + 1);
  if (n > keys.length) { skipped.push(`${cls}/${slot} (${name}): more rows than slots`); continue; }
  p[keys[n - 1]] = { id, name };
  if (keys.length === 2 && n === 1) p[keys[1]] = { id, name }; // overwritten if a second row follows
}

fs.writeFileSync(
  outPath,
  '/* Generated by scripts/bis-presets-to-js.mjs from the BiS CSV — do not edit. Enables file:// without CORS. */\n' +
  'window.__DPS_BIS_PRESETS__=' + JSON.stringify(presets) + ';\n'
);
console.log('Wrote', outPath, '—', Object.keys(presets).length, 'classes');
skipped.forEach(s => console.log('  skipped:', s));
