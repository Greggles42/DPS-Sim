/**
 * Emit resources/npc_types-data.js so index.html can load NPC types via <script> when opened as file://
 * (fetch() to local JSON is blocked by CORS).
 * Run: node scripts/npc-types-to-js.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const res = path.join(__dirname, '..', 'resources');
const jsonPath = path.join(res, 'npc_types.json');
const outPath = path.join(res, 'npc_types-data.js');

console.log('Reading', jsonPath);
const raw = fs.readFileSync(jsonPath, 'utf8');
console.log('Parsing JSON (large file, may take a moment)...');
const data = JSON.parse(raw);
if (!Array.isArray(data)) {
  console.error('Expected npc_types.json to be a JSON array');
  process.exit(1);
}
console.log('Serializing', data.length, 'NPC types...');
const js =
  '/* Generated by scripts/npc-types-to-js.mjs — do not edit. Enables file:// without CORS. */\n' +
  'window.__DPS_NPC_TYPES__=' +
  JSON.stringify(data) +
  ';\n';
fs.writeFileSync(outPath, js);
console.log('Wrote', outPath);
