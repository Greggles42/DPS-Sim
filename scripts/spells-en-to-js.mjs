/**
 * Emit resources/spells-data.js so spell proc lookups work when opening index.html as file://
 * (fetch to spells_en.json is CORS-blocked).
 * Run: node scripts/spells-en-to-js.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const res = path.join(__dirname, '..', 'resources');
const jsonPath = path.join(res, 'spells_en.json');
const outPath = path.join(res, 'spells-data.js');

console.log('Reading', jsonPath);
const raw = fs.readFileSync(jsonPath, 'utf8');
console.log('Parsing spells JSON (may take a moment)...');
const data = JSON.parse(raw);
if (!data || typeof data !== 'object') {
  console.error('Expected spells_en.json to be a JSON object');
  process.exit(1);
}
console.log('Writing bundle...');
const js =
  '/* Generated by scripts/spells-en-to-js.mjs — do not edit. Enables file:// without CORS. */\n' +
  'window.__DPS_SPELLS_EN__=' +
  JSON.stringify(data) +
  ';\n';
fs.writeFileSync(outPath, js);
console.log('Wrote', outPath);
